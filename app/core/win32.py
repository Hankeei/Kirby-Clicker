# -- helpers ---------------------------------------------------------------
def get_cursor_pos() -> tuple[int, int]:
    pt = wintypes.POINT()
    user32.GetCursorPos(ctypes.byref(pt))
    return int(pt.x), int(pt.y)


def window_under_point(x: int, y: int) -> tuple[int, int, int]:
    """Return (deepest hwnd, root hwnd, pid) under a screen coordinate."""
    hwnd = int(user32.WindowFromPoint(wintypes.POINT(int(x), int(y))) or 0)
    if not hwnd:
        return 0, 0, 0
    root = int(user32.GetAncestor(hwnd, GA_ROOT) or hwnd)
    pid = wintypes.DWORD()
    user32.GetWindowThreadProcessId(root, ctypes.byref(pid))
    return hwnd, root, int(pid.value)


def is_window(hwnd: int) -> bool:
    return bool(user32.IsWindow(hwnd))


def window_pid(hwnd: int) -> int:
    pid = wintypes.DWORD()
    user32.GetWindowThreadProcessId(hwnd, ctypes.byref(pid))
    return int(pid.value)


def window_title(hwnd: int) -> str:
    length = user32.GetWindowTextLengthW(hwnd)
    if length <= 0:
        return ""
    buf = ctypes.create_unicode_buffer(length + 1)
    user32.GetWindowTextW(hwnd, buf, length + 1)
    return buf.value


def process_exe(pid: int) -> str:
    if not pid:
        return ""
    handle = kernel32.OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, False, pid)
    if not handle:
        return ""
    try:
        size = wintypes.DWORD(32768)
        buf = ctypes.create_unicode_buffer(size.value)
        if kernel32.QueryFullProcessImageNameW(handle, 0, buf, ctypes.byref(size)):
            return os.path.basename(buf.value)
        return ""
    finally:
        kernel32.CloseHandle(handle)


def is_cloaked(hwnd: int) -> bool:
    try:
        cloaked = wintypes.DWORD(0)
        dwmapi.DwmGetWindowAttribute(hwnd, DWMWA_CLOAKED, ctypes.byref(cloaked), ctypes.sizeof(cloaked))
        return bool(cloaked.value)
    except Exception:
        return False


def _pack_point(x: int, y: int) -> int:
    return ((int(y) & 0xFFFF) << 16) | (int(x) & 0xFFFF)


_BUTTON_WORDS = {
    "left": (WM_LBUTTONDOWN, WM_LBUTTONUP, MK_LBUTTON, MOUSEEVENTF_LEFTDOWN, MOUSEEVENTF_LEFTUP),
    "right": (WM_RBUTTONDOWN, WM_RBUTTONUP, MK_RBUTTON, MOUSEEVENTF_RIGHTDOWN, MOUSEEVENTF_RIGHTUP),
    "middle": (WM_MBUTTONDOWN, WM_MBUTTONUP, MK_MBUTTON, MOUSEEVENTF_MIDDLEDOWN, MOUSEEVENTF_MIDDLEUP),
}


def post_mouse_message(hwnd: int, button: str, down: bool, screen_x: int, screen_y: int) -> bool:
    """Post WM_xBUTTON(DOWN/UP) to a window using client coordinates."""
    if button not in _BUTTON_WORDS:
        return False
    down_msg, up_msg, down_mask, _, _ = _BUTTON_WORDS[button]
    pt = wintypes.POINT(int(screen_x), int(screen_y))
    if not user32.ScreenToClient(hwnd, ctypes.byref(pt)):
        return False
    msg = down_msg if down else up_msg
    wparam = down_mask if down else 0
    return bool(user32.PostMessageW(hwnd, msg, wparam, _pack_point(pt.x, pt.y)))


def send_mouse_button(button: str, down: bool) -> bool:
    if button not in _BUTTON_WORDS:
        return False
    _, _, _, down_flag, up_flag = _BUTTON_WORDS[button]
    inp = INPUT()
    inp.type = INPUT_MOUSE
    inp.union.mi = MOUSEINPUT(0, 0, 0, down_flag if down else up_flag, 0, 0)
    return user32.SendInput(1, ctypes.byref(inp), ctypes.sizeof(INPUT)) == 1


def get_double_click_time() -> int:
    return int(user32.GetDoubleClickTime())


